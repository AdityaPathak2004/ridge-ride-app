import assert from 'node:assert/strict';
import {DATA,DEFAULTS,localParts,epoch,daily,upcoming,conflicts} from './dist/schedule.js';
const day='2026-09-15',cfg={...DEFAULTS,outbound:7,wait:3,inbound:8};
assert.equal(DATA.villas.length,47);
assert.equal(daily(day,'campus').length,45);
assert.equal(upcoming(epoch(day,420),'campus')[0].minute,430);
assert.equal(upcoming(epoch(day,431),'campus')[0].minute,450);
assert.equal(upcoming(epoch(day,430)+45000,'campus')[0].minute,430);
assert.equal(upcoming(epoch(day,430)+45000,'campus',DEFAULTS,3,true)[0].minute,450);
assert.equal(upcoming(epoch(day,610),'campus')[0].minute,630);
assert.equal(upcoming(epoch(day,971),'campus')[0].minute,990);
assert.equal(upcoming(epoch(day,1371),'campus')[0].serviceDate,'2026-09-16');
assert.equal(upcoming(epoch('2026-09-18',1380),'campus')[0].serviceDate,'2026-09-21');
assert.equal(daily('2026-09-20','campus').length,0);
assert.equal(daily(day,'home').length,0);
assert.equal(daily(day,'home',cfg)[0].minute,440);
assert.equal(daily(day,'home',cfg)[0].arrival,epoch(day,448));
const late={...cfg,outbound:90,wait:0};
assert.equal(localParts(new Date(daily(day,'home',late).at(-1).at)).date,'2026-09-16');
assert.equal(upcoming(epoch('2026-09-16',1),'home',late)[0].serviceDate,day);
assert.equal(new Date(epoch(day,430)).toISOString(),'2026-09-15T11:10:00.000Z');
assert.equal(new Date(epoch('2026-12-15',430)).toISOString(),'2026-12-15T12:10:00.000Z');
assert.equal(conflicts({...cfg,singleBus:true}).length,3);
assert.equal(daily(day,'campus',{...cfg,breakMode:'include'}).length,47);
console.log('20 schedule checks passed: departures, breaks, weekends, midnight, estimates, DST and turnaround conflicts.');
